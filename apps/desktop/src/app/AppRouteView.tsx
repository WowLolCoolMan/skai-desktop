export function AppRouteView({ state, actions }: { state: AppRouteState; actions: AppRouteActions }) {
  const { route } = state;
  const chat = (workspaceMode: "conversation" | "project" = "conversation") => <ChatPage workspaceTabId={state.workspaceTabId} capacity={state.capacity} provider={state.provider} model={state.model} responseMode={state.responseMode} onResponseModeChange={actions.onResponseModeChange} endpoint={state.endpoint} models={state.models} messages={state.messages} busy={state.busy} taskBusy={state.taskBusy} tasks={state.tasks} scheduledTasks={state.scheduledTasks} attachments={state.attachments} queuedMessages={state.queuedMessages} conversationId={state.conversationId} conversationTitle={state.conversationTitle} pinned={state.pinned} archived={state.archived} smartPromptRewritingEnabled={state.smartPromptRewritingEnabled} onRewritePrompt={actions.onRewritePrompt} onSend={actions.onSend} onStartTemporaryChat={actions.onStartTemporaryChat} onQueue={actions.onQueue} onRemoveQueued={actions.onRemoveQueued} onAttach={actions.onAttach} onFilesDropped={actions.onFilesDropped} onRemoveAttachment={actions.onRemoveAttachment} onSetAttachments={actions.onSetAttachments} onModelChange={actions.onModelChange} onNavigate={actions.onNavigate} onTaskAction={actions.onTaskAction} onOpenFile={actions.onOpenFile} onPlanTask={actions.onPlanTask} onScheduleTask={actions.onScheduleTask} onTransitionScheduledTask={actions.onTransitionScheduledTask} onExport={actions.onExportConversations} onPreviewImport={actions.onPreviewConversationImport} onApplyImport={actions.onApplyConversationImport} onFork={actions.onFork} onForkFromMessage={actions.onForkFromMessage} onRetryMessage={actions.onRetryMessage} onEditMessage={actions.onEditMessage} onTogglePinned={actions.onTogglePinned} onArchive={actions.onArchive} onRenameConversation={actions.onRenameConversation} workspaceMode={workspaceMode} onNewWorkspaceTab={actions.onNewWorkspaceTab} />;
  if (route === "chat") return chat();
  if (route === "scheduled") return <ScheduledPage scheduledTasks={state.scheduledTasks} busyTask={state.taskBusy} loading={state.tasksLoading} loadError={state.tasksError} onRetry={actions.onRetryWorkbench} onSchedule={actions.onScheduleTask} onTransition={actions.onTransitionScheduledTask} />;
  if (route === "compare") return <ComparePage models={state.models} onNavigate={actions.onNavigate} onCompareModel={actions.onCompareModel} />;
  if (route === "coding" || route === "projects") {
    const editor = <CodingPage conversation={route === "coding" && state.selectedProject ? chat("project") : undefined} messages={state.messages} sideChatRequest={state.sideChatRequest} onNewWorkspaceTab={actions.onNewWorkspaceTab} onNewProjectThread={actions.onNewProjectThread} onStartSubagent={actions.onStartSubagent} projectDirectory={route === "projects"} projects={state.projects} tasks={state.tasks} selectedProject={state.selectedProject} projectFiles={state.projectFiles} selectedFile={state.selectedFile} filePreview={state.filePreview} filePreviewError={state.filePreviewError} fileDraft={state.fileDraft} fileOriginal={state.fileOriginal} fileSummary={state.fileSummary} fileBusy={state.fileBusy} fileUndoAvailable={state.fileUndoAvailable} terminalBusy={state.terminalBusy} terminalOutput={state.terminalOutput} terminalExitCode={state.terminalExitCode} gitStatus={state.gitStatus} gitBusy={state.gitBusy} gitDiff={state.gitDiff} gitDiffBusy={state.gitDiffBusy} gitCommitBusy={state.gitCommitBusy} gitPushBusy={state.gitPushBusy ?? false} gitPullRequestBusy={state.gitPullRequestBusy ?? false} projectChecks={state.projectChecks} projectChecksBusy={state.projectChecksBusy} projectCheckBusy={state.projectCheckBusy} onLoadProjectChecks={actions.onLoadProjectChecks ?? (() => undefined)} onRunProjectCheck={actions.onRunProjectCheck ?? (async () => undefined)} onCancelTask={(id) => actions.onTransitionTask(id, "cancel")} onRefreshGitStatus={actions.onRefreshGitStatus} onLoadGitDiff={actions.onLoadGitDiff} onCommitGitChanges={actions.onCommitGitChanges} onPushGitChanges={actions.onPushGitChanges ?? (async () => false)} onCreateGitPullRequest={actions.onCreateGitPullRequest ?? (async () => false)} onPickFolder={actions.onPickFolder} onSaveProject={actions.onSaveProject} onOpenProject={actions.onOpenProject} onOpenFile={actions.onOpenFile} onCloseFile={actions.onCloseFile} onDraftChange={actions.onDraftChange} onSaveFile={actions.onSaveFile} onUndoFile={actions.onUndoFile} onRunTerminal={actions.onRunTerminal} onRunProjectPreflight={actions.onRunProjectPreflight} onNavigate={actions.onNavigate} />;
    return editor;
  }
  if (route === "settings") return <SettingsPage provider={state.provider} endpoint={state.endpoint} model={state.model} models={state.models} ollamaContextWindowTokens={state.ollamaContextWindowTokens ?? 0} localRamBudgetBytes={state.localRamBudgetBytes} localGpuBudgetBytes={state.localGpuBudgetBytes} themeMode={state.themeMode} accentColor={state.accentColor} density={state.density} backdrop={state.backdrop} reduceMotion={state.reduceMotion} petVisible={state.petVisible} petWander={state.petWander} petInteractionDemo={state.petInteractionDemo} petCharacter={state.petCharacter} petSpriteDataUrl={state.petSpriteDataUrl} developerMode={state.developerMode} memoryInjectionEnabled={state.memoryInjectionEnabled} smartPromptRewritingEnabled={state.smartPromptRewritingEnabled} imageEndpoint={state.imageEndpoint} imageWorkflow={state.imageWorkflow} onChange={actions.onSettingsChange} onSave={actions.onSaveSettings} onDiscoverModels={actions.onDiscoverModels} onImageChange={actions.onImageChange} onExportMemory={actions.onExportMemory} onNavigate={actions.onNavigate} />;
  if (route === "pet-workshop") return <PetWorkshopPage onReturnToWork={() => actions.onNavigate("chat")} />;
  if (route === "voice-workbench") return <div className="feature-page voice-workbench-page"><VoiceWorkbench onBack={() => actions.onNavigate("marketplace")} /></div>;
  if (route === "models") return <ModelsPage models={state.models} onDiscover={actions.onDiscoverModels} onPull={actions.onPullModel} onCancelPull={actions.onCancelModelPull ?? (async () => false)} onSelect={actions.onSelectModel} />;
  if (route === "images") return <ImagesPage provider={state.imageProvider} endpoint={state.imageEndpoint} prompt={state.imagePrompt} workflow={state.imageWorkflow} busy={state.imageBusy} cancelRequested={state.imageCancelRequested} progress={state.imageProgress} images={state.generatedImages} onChange={actions.onImageChange} onGenerate={actions.onGenerateImage} onCancel={actions.onCancelImageGeneration ?? (async () => false)} onImportWorkflow={actions.onImportWorkflow ?? (async () => null)} onPickSourceImage={actions.onPickImageSource ?? (async () => null)} />;
  if (route === "video") return <VideoPage />;
  // Marketplace is the unified capabilities catalog. Keep the legacy plugins
  // route as an alias so existing deep links continue to work, but render the
  // Plugins-style catalog as the single entry point.
  if (route === "marketplace") return <PluginsPage onNavigate={(nextRoute) => actions.onNavigate(nextRoute)} onSelectAirLlmModel={actions.onSelectModel} onImageChange={(key, value) => actions.onImageChange(key, value)} onImportWorkflow={actions.onImportWorkflow} />;
  if (route === "memory") return <MemoryPage entries={state.memoryEntries} busy={state.memoryBusy} loading={state.memoryLoading} error={state.memoryError} onRetry={actions.onRetryMemory} onSearch={actions.onSearchMemory} onSave={actions.onSaveMemory} onToggle={actions.onToggleMemory} onRemove={actions.onRemoveMemory} onExport={actions.onExportMemory} corpusDocuments={state.corpusDocuments} corpusLoading={state.corpusLoading} corpusError={state.corpusError} onSearchCorpus={actions.onSearchCorpus ?? (() => undefined)} onSaveCorpus={actions.onSaveCorpus ?? (async () => false)} onRemoveCorpus={actions.onRemoveCorpus ?? (async () => false)} onImportCorpus={actions.onImportCorpus ?? (() => undefined)} />;
  if (route === "usage") return <UsagePage conversations={state.conversations} projects={state.projects} tasks={state.tasks} scheduledTasks={state.scheduledTasks} memoryCount={state.memoryEntries.length} corpusCount={state.corpusDocuments.length} savedImageCount={state.generatedImages.length} provider={state.provider} model={state.model} capacity={state.capacity} />;
  if (route === "persona-workshop" || route === "personas" || route === "persona-groups") return <PersonaWorkshopPage personas={state.personas ?? []} endpoint={state.endpoint} model={state.model} provider={state.provider} />;
  return <TerminalPage projects={state.projects} initialProjectId={state.selectedProject?.id} projectFiles={state.projectFiles} gitStatus={state.gitStatus} busy={state.terminalBusy} output={state.terminalOutput} exitCode={state.terminalExitCode} sessionId={state.terminalSessionId ?? null} screen={state.terminalScreen ?? null} onRun={actions.onRunProjectCommand} onRunPreflight={actions.onRunProjectPreflight} onRefreshGit={actions.onRefreshGitStatus} onOpenFile={(path) => { actions.onOpenFile(path); actions.onNavigate("coding"); }} onSelectProject={actions.onSelectProject} onStartSession={actions.onStartTerminalSession ?? (async () => false)} onWriteSession={actions.onWriteTerminalSession ?? (async () => false)} onRefreshSession={actions.onRefreshTerminalSession ?? (async () => false)} onCloseSession={actions.onCloseTerminalSession ?? (async () => true)} onOpenCoding={() => actions.onNavigate("coding")} />;
}
