// Generated theme files: the built-in "Skai" family (dark + light) is built
// from tokens.css and docs/theme.schema.json from the validator's key lists,
// so neither drifts. scripts/test-theme-files.cjs fails when either is stale;
// run `node scripts/theme-generate.cjs --write` to regenerate both.
const fs = require("node:fs");
const path = require("node:path");
const { COLOR_KEYS, GRADIENT_SURFACES, FONT_ROLES, tokenForColorKey, parseColor } = require("../apps/desktop/electron/theme-files.cjs");

const root = path.resolve(__dirname, "..");
const tokensPath = path.join(root, "apps", "desktop", "src", "design-system", "tokens.css");
const presetPath = path.join(root, "apps", "desktop", "src", "theme", "presets", "skai.json");
const schemaPath = path.join(root, "docs", "theme.schema.json");

function block(css, selector) {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`${selector} block not found in tokens.css`);
  const body = css.slice(css.indexOf("{", start) + 1, css.indexOf("\n}", start));
  return Object.fromEntries([...body.matchAll(/(--[a-z0-9-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
}

function buildSkaiFamily() {
  const css = fs.readFileSync(tokensPath, "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  const dark = block(css, ":root");
  const light = { ...dark, ...block(css, '[data-scheme="light"]') };
  const colors = (tokens) => Object.fromEntries(COLOR_KEYS.map((key) => [key, parseColor(tokens[tokenForColorKey(key)] ?? "")]).filter(([, value]) => value));
  return {
    $schema: "../../../../../docs/theme.schema.json",
    name: "Skai",
    author: "Skai Desktop",
    license: "Original Skai Desktop theme (same license as the app)",
    themes: [
      { name: "Skai Dark", appearance: "dark", colors: colors(dark) },
      { name: "Skai Light", appearance: "light", colors: colors(light) },
    ],
  };
}

function buildSchema() {
  const color = { type: "string", maxLength: 64, description: "#rgb, #rgba, #rrggbb, #rrggbbaa, rgb()/rgba(), hsl()/hsla() with plain numbers, or transparent. Nothing else (no url(), var() or keywords)." };
  const gradient = {
    oneOf: [
      { $ref: "#/$defs/color" },
      {
        type: "object", additionalProperties: false, required: ["gradient", "stops"],
        properties: {
          gradient: { enum: ["linear", "radial", "conic"] },
          angle: { type: "number", minimum: 0, maximum: 360, description: "Degrees, for linear and conic. Default 180 (top to bottom)." },
          stops: { type: "array", minItems: 2, maxItems: 8, items: { type: "object", additionalProperties: false, required: ["color", "at"], properties: { color: { $ref: "#/$defs/color" }, at: { type: "number", minimum: 0, maximum: 1 } } } },
        },
      },
    ],
  };
  const font = {
    type: "object", additionalProperties: false,
    properties: {
      family: { description: "Up to 4 plain font names, first one wins (letters, digits, space, _ . -).", oneOf: [{ type: "string", maxLength: 300 }, { type: "array", maxItems: 4, items: { type: "string", pattern: "^[A-Za-z0-9][A-Za-z0-9 _.\\-]{0,62}$" } }] },
      size: { type: "number", minimum: 8, maximum: 32, description: "px" },
      weight: { type: "number", minimum: 100, maximum: 900 },
      lineHeight: { type: "number", minimum: 1, maximum: 2.5 },
      letterSpacing: { type: "number", minimum: -0.1, maximum: 0.3, description: "em" },
    },
  };
  return {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: "urn:skai-desktop:theme-schema:1",
    title: "Skai Desktop theme family",
    description: "Generated by scripts/theme-generate.cjs from the validator in apps/desktop/electron/theme-files.cjs. See docs/THEMING.md.",
    type: "object", required: ["name", "themes"],
    properties: {
      $schema: { type: "string" },
      name: { type: "string", minLength: 1, maxLength: 64 },
      author: { type: "string", maxLength: 160 },
      license: { type: "string", maxLength: 160 },
      themes: {
        type: "array", minItems: 1, maxItems: 16,
        items: {
          type: "object", required: ["name", "appearance"],
          properties: {
            name: { type: "string", minLength: 1, maxLength: 64 },
            appearance: { enum: ["light", "dark"] },
            colors: { type: "object", additionalProperties: false, properties: Object.fromEntries(COLOR_KEYS.map((key) => [key, { $ref: "#/$defs/color", description: `Sets ${tokenForColorKey(key)}` }])) },
            gradients: { type: "object", additionalProperties: false, properties: Object.fromEntries(GRADIENT_SURFACES.map((key) => [key, { $ref: "#/$defs/gradient" }])) },
            fonts: { type: "object", additionalProperties: false, properties: Object.fromEntries(FONT_ROLES.map((key) => [key, { $ref: "#/$defs/font" }])) },
          },
        },
      },
    },
    $defs: { color, gradient, font },
  };
}

const serialize = (value) => `${JSON.stringify(value, null, 2)}\n`;
if (require.main === module && process.argv.includes("--write")) {
  fs.writeFileSync(presetPath, serialize(buildSkaiFamily()));
  fs.writeFileSync(schemaPath, serialize(buildSchema()));
  console.log(`Wrote ${path.relative(root, presetPath)} and ${path.relative(root, schemaPath)}`);
}
module.exports = { buildSkaiFamily, buildSchema, serialize, presetPath, schemaPath };
